"""Load declarative contracts (YAML or JSON) into :class:`Operation` objects.

Files are validated against :data:`CONTRACT_SCHEMA` and then against the same
checks as Python-defined contracts. Files with ``status: draft`` (for example
generated by an importer) are refused until a reviewer changes the status.
Custom Python transforms cannot be referenced from files except by name via
``Gateway(transforms={...})``.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from jsonschema import Draft202012Validator

from toolbound.core.contracts import (
    ApiKeyAuth,
    Auth,
    BasicAuth,
    BearerAuth,
    Field,
    FieldSpec,
    Limits,
    NetworkPolicy,
    NoAuth,
    Operation,
    Output,
    Pagination,
    RateLimit,
    RetryPolicy,
    Service,
)
from toolbound.core.errors import ConfigurationError
from toolbound.core.paths import parse_path

from .meta_schema import CONTRACT_SCHEMA

_VALIDATOR = Draft202012Validator(CONTRACT_SCHEMA)
_SUFFIXES = (".yaml", ".yml", ".json")

__all__ = ["CONTRACT_SCHEMA", "load_contract_file", "load_contracts", "parse_contract"]


def load_contracts(path: str | Path) -> list[Operation]:
    """Load one file, or every ``*.yaml|*.yml|*.json`` file in a directory (sorted)."""
    root = Path(path)
    if root.is_dir():
        files = sorted(p for p in root.iterdir() if p.suffix in _SUFFIXES and p.is_file())
        if not files:
            raise ConfigurationError(f"no contract files found in {root}")
        operations: list[Operation] = []
        for file in files:
            operations.extend(load_contract_file(file))
        return operations
    return load_contract_file(root)


def load_contract_file(path: str | Path) -> list[Operation]:
    file = Path(path)
    text = file.read_text(encoding="utf-8")
    if file.suffix == ".json":
        document = json.loads(text)
    elif file.suffix in (".yaml", ".yml"):
        try:
            import yaml
        except ImportError as exc:  # pragma: no cover - depends on environment
            raise ConfigurationError(
                "YAML contracts need PyYAML: pip install 'toolbound[yaml]'"
            ) from exc
        document = yaml.safe_load(text)
    else:
        raise ConfigurationError(f"unsupported contract file type: {file.name}")
    try:
        return parse_contract(document)
    except ConfigurationError as exc:
        raise ConfigurationError(f"{file}: {exc}") from exc


def parse_contract(document: Any) -> list[Operation]:
    """Validate a parsed contract document and build its operations."""
    errors = sorted(_VALIDATOR.iter_errors(document), key=lambda e: list(e.absolute_path))
    if errors:
        first = errors[0]
        where = "/".join(str(p) for p in first.absolute_path) or "(root)"
        raise ConfigurationError(f"invalid contract at {where}: {first.message}")
    if document.get("status", "active") == "draft":
        raise ConfigurationError(
            "contract is marked 'status: draft'; review it and set 'status: active' to load it"
        )
    service = _service(document["service"])
    return [_operation(op, service) for op in document["operations"]]


def _service(raw: dict[str, Any]) -> Service:
    return Service(
        name=raw["name"],
        base_url=raw["base_url"],
        auth=_auth(raw.get("auth")),
        headers=raw.get("headers", {}),
        network=_network(raw.get("network", {})),
        limits=Limits(**raw.get("limits", {})),
        retry=_retry(raw.get("retry", {})),
    )


def _auth(raw: dict[str, Any] | None) -> Auth:
    if raw is None or raw["type"] == "none":
        return NoAuth()
    credential = raw.get("credential")
    if not credential:
        raise ConfigurationError(f"auth type {raw['type']!r} needs 'credential'")
    if raw["type"] == "bearer":
        return BearerAuth(credential)
    if raw["type"] == "basic":
        return BasicAuth(credential)
    if "query" in raw:
        return ApiKeyAuth(credential, header=None, query=raw["query"])
    return ApiKeyAuth(credential, header=raw.get("header", "X-API-Key"))


def _network(raw: dict[str, Any]) -> NetworkPolicy:
    return NetworkPolicy(
        allow_hosts=tuple(raw.get("allow_hosts", ())),
        allow_ports=tuple(raw.get("allow_ports", ())),
        allow_http=raw.get("allow_http", False),
        allow_networks=tuple(raw.get("allow_networks", ())),
        follow_redirects=raw.get("follow_redirects", False),
        max_redirects=raw.get("max_redirects", 3),
    )


def _retry(raw: dict[str, Any]) -> RetryPolicy:
    data = dict(raw)
    if "retry_statuses" in data:
        data["retry_statuses"] = frozenset(data["retry_statuses"])
    return RetryPolicy(**data)


def _shape(raw: dict[str, Any] | None) -> dict[str, FieldSpec] | None:
    if raw is None:
        return None
    shape: dict[str, FieldSpec] = {}
    for key, value in raw.items():
        parse_path(value if isinstance(value, str) else value["from"])  # fail early
        if isinstance(value, str):
            shape[key] = value
        else:
            kwargs: dict[str, Any] = {
                "source": value["from"],
                "max_chars": value.get("max_chars"),
                "max_items": value.get("max_items"),
                "transform": value.get("transform"),
                "shape": _shape(value.get("shape")),
            }
            if "default" in value:
                kwargs["default"] = value["default"]
            shape[key] = Field(**kwargs)
    return shape


def _output(raw: dict[str, Any] | None) -> Output:
    if not raw:
        return Output()
    data = dict(raw)
    parse_path(raw.get("root", "$"))
    data["shape"] = _shape(raw.get("shape"))
    data["error_shape"] = _shape(raw.get("error_shape"))
    if "required" in data:
        data["required"] = tuple(data["required"])
    if "redact_keys" in data:
        data["redact_keys"] = tuple(data["redact_keys"])
    return Output(**data)


def _operation(raw: dict[str, Any], service: Service) -> Operation:
    rate = raw.get("rate_limit")
    pagination = raw.get("pagination")
    return Operation(
        name=raw["name"],
        description=raw["description"],
        service=service,
        method=raw.get("method", "GET"),
        path=raw["path"],
        effect=raw.get("effect", "read"),
        input=raw.get("input", {}),
        bind=raw.get("bind", {}),
        required_scopes=tuple(raw.get("required_scopes", ())),
        tags=tuple(raw.get("tags", ())),
        group=raw.get("group"),
        requires_approval=raw.get("requires_approval"),
        rate_limit=RateLimit(**rate) if rate else None,
        query=tuple(raw["query"]) if "query" in raw else None,
        body=tuple(raw["body"]) if "body" in raw else None,
        body_format=raw.get("body_format", "json"),
        headers=raw.get("headers", {}),
        idempotency_header=raw.get("idempotency_header"),
        pagination=Pagination(**pagination) if pagination else None,
        output=_output(raw.get("output")),
    )
